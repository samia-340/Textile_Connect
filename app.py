import io
import requests
import sqlite3
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd
import qrcode
import streamlit as st

st.set_page_config(page_title="ZWARK Connect | Contract Visibility", page_icon="🔗", layout="wide")
DB = Path(__file__).with_name("zwark_connect.db")


def connect():
    db = sqlite3.connect(DB, timeout=15)
    db.row_factory = sqlite3.Row
    db.execute("PRAGMA foreign_keys = ON")
    return db


def init_db():
    with connect() as db:
        db.executescript("""
        CREATE TABLE IF NOT EXISTS contracts (
          id INTEGER PRIMARY KEY AUTOINCREMENT,
          ref TEXT NOT NULL UNIQUE,
          supplier TEXT NOT NULL,
          mill TEXT NOT NULL,
          material TEXT NOT NULL,
          batch TEXT NOT NULL,
          quantity REAL NOT NULL CHECK(quantity > 0),
          created_at TEXT NOT NULL
        );
        CREATE TABLE IF NOT EXISTS shipments (
          id INTEGER PRIMARY KEY AUTOINCREMENT,
          contract_id INTEGER NOT NULL REFERENCES contracts(id),
          quantity REAL NOT NULL CHECK(quantity > 0),
          dispatched_at TEXT NOT NULL,
          received_quantity REAL,
          received_at TEXT,
          CHECK(received_quantity IS NULL OR (received_quantity >= 0 AND received_quantity <= quantity))
        );
        CREATE TABLE IF NOT EXISTS contract_mappings (
          contract_id INTEGER PRIMARY KEY REFERENCES contracts(id),
          mill_order_ref TEXT NOT NULL UNIQUE
        );
        CREATE TABLE IF NOT EXISTS api_imports (
          external_record_id INTEGER NOT NULL,
          mill_order_ref TEXT NOT NULL,
          production_id INTEGER NOT NULL REFERENCES production(id),
          imported_at TEXT NOT NULL,
          PRIMARY KEY (external_record_id, mill_order_ref)
        );
        CREATE TABLE IF NOT EXISTS production (
          id INTEGER PRIMARY KEY AUTOINCREMENT,
          contract_id INTEGER NOT NULL REFERENCES contracts(id),
          shift_date TEXT NOT NULL,
          shift TEXT NOT NULL,
          yarn_used REAL NOT NULL CHECK(yarn_used >= 0),
          yarn_waste REAL NOT NULL CHECK(yarn_waste >= 0),
          fabric_m REAL NOT NULL CHECK(fabric_m >= 0),
          notes TEXT NOT NULL DEFAULT '',
          created_at TEXT NOT NULL
        );
        """)


def now():
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


def rows(sql, params=()):
    with connect() as db:
        return [dict(r) for r in db.execute(sql, params).fetchall()]


def scalar(sql, params=()):
    with connect() as db:
        return db.execute(sql, params).fetchone()[0] or 0


def qr_png(value):
    img = qrcode.make(value)
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    return buf.getvalue()


init_db()
st.title("ZWARK Connect")
st.caption("Contract-based textile supply chain visibility")
st.info("Demo mode: Switch between supplier and mill views. This is not real authentication, and the SQLite database is intended for local demonstration only.")
role = st.sidebar.radio("View as", ["Yarn Supplier", "Weaving Mill"])
st.sidebar.markdown("**Demo companies**")
st.sidebar.write("Supplier: Atlas Yarn Traders")
st.sidebar.write("Mill: Crescent Weaving Mills")
st.sidebar.caption("Quantities in kilograms unless marked otherwise. Shift records can be generated by the simulated mill API or entered manually.")

contracts = rows("SELECT * FROM contracts ORDER BY id DESC")

if role == "Yarn Supplier":
    t1, t2, t3, t4 = st.tabs(["Contracts", "Dispatch & QR", "Production Visibility", "API Integration"])
    with t1:
        st.subheader("Create a shared contract")
        with st.form("contract_form", clear_on_submit=True):
            a, b = st.columns(2)
            ref = a.text_input("Shared contract reference", placeholder="ZW-001")
            material = b.text_input("Yarn description", value="30/1 Cotton Yarn")
            batch = a.text_input("Yarn batch", placeholder="YB-101")
            quantity = b.number_input("Contract quantity (kg)", min_value=0.01, value=1000.0, step=50.0)
            submit = st.form_submit_button("Create contract", type="primary")
        if submit:
            if not ref.strip() or not material.strip() or not batch.strip():
                st.error("Enter a contract reference, yarn description, and batch.")
            else:
                try:
                    with connect() as db:
                        db.execute("INSERT INTO contracts (ref,supplier,mill,material,batch,quantity,created_at) VALUES (?,?,?,?,?,?,?)", (ref.strip(), "Atlas Yarn Traders", "Crescent Weaving Mills", material.strip(), batch.strip(), quantity, now()))
                    st.success("Contract created. Open Dispatch & QR to create a shipment.")
                    st.rerun()
                except sqlite3.IntegrityError:
                    st.error("That contract reference already exists.")
        if contracts:
            st.dataframe(pd.DataFrame(contracts)[["ref", "supplier", "mill", "material", "batch", "quantity", "created_at"]], hide_index=True, use_container_width=True)
        else:
            st.caption("No contracts yet. Create your first contract above.")
    with t2:
        st.subheader("Dispatch yarn")
        if contracts:
            chosen = st.selectbox("Contract", contracts, format_func=lambda x: f"{x['ref']} · {x['material']} · {x['quantity']:,.1f} kg", key="dispatch_contract")
            dispatched = scalar("SELECT COALESCE(SUM(quantity),0) FROM shipments WHERE contract_id=?", (chosen["id"],))
            remaining = max(0.0, chosen["quantity"] - dispatched)
            st.metric("Quantity not yet dispatched", f"{remaining:,.1f} kg")
            if remaining > 0:
                with st.form("shipment_form"):
                    qty = st.number_input("Dispatch quantity (kg)", min_value=0.01, max_value=float(remaining), value=float(remaining))
                    create_shipment = st.form_submit_button("Create shipment", type="primary")
                if create_shipment:
                    with connect() as db:
                        db.execute("INSERT INTO shipments (contract_id,quantity,dispatched_at) VALUES (?,?,?)", (chosen["id"], qty, now()))
                    st.success("Shipment created. Share its QR code with the mill.")
                    st.rerun()
            ships = rows("SELECT * FROM shipments WHERE contract_id=? ORDER BY id DESC", (chosen["id"],))
            for ship in ships:
                status = "Received" if ship["received_at"] else "Awaiting receipt"
                with st.expander(f"Shipment #{ship['id']} · {ship['quantity']:,.1f} kg · {status}", expanded=(ship == ships[0])):
                    token = f"ZWARK-CONNECT|SHIPMENT:{ship['id']}|CONTRACT:{chosen['ref']}"
                    st.image(qr_png(token), width=180, caption="Shipment identification QR")
                    st.code(token)
                    st.download_button("Download QR image", qr_png(token), file_name=f"zwark_shipment_{ship['id']}.png", mime="image/png", key=f"download_{ship['id']}")
                    if ship["received_at"]:
                        st.write(f"Confirmed received: {ship['received_quantity']:,.1f} kg on {ship['received_at']}")
                    else:
                        st.write("Receipt pending")
        else:
            st.info("Create a contract first.")
    with t3:
        st.subheader("Supplier visibility into mill operations")
        if contracts:
            chosen = st.selectbox("Contract", contracts, format_func=lambda x: x["ref"], key="supplier_progress")
            received = scalar("SELECT COALESCE(SUM(received_quantity),0) FROM shipments WHERE contract_id=?", (chosen["id"],))
            used = scalar("SELECT COALESCE(SUM(yarn_used),0) FROM production WHERE contract_id=?", (chosen["id"],))
            waste = scalar("SELECT COALESCE(SUM(yarn_waste),0) FROM production WHERE contract_id=?", (chosen["id"],))
            fabric = scalar("SELECT COALESCE(SUM(fabric_m),0) FROM production WHERE contract_id=?", (chosen["id"],))
            a,b,c,d = st.columns(4)
            a.metric("Yarn received", f"{received:,.1f} kg")
            b.metric("Yarn used", f"{used:,.1f} kg")
            c.metric("Yarn wasted", f"{waste:,.1f} kg")
            d.metric("Fabric produced", f"{fabric:,.1f} m")
            st.progress(min(1.0, (used + waste) / received) if received else 0, text=f"{((used+waste)/received*100 if received else 0):.1f}% of received yarn accounted for as used or wasted")
            st.caption(f"Unallocated received yarn (illustrative balance): {received-used-waste:,.1f} kg")
            if used + waste > received + 1e-6:
                st.warning("Reported yarn used + wasted exceeds received quantity. Check the recorded figures.")
            prod = rows("SELECT shift_date,shift,yarn_used,yarn_waste,fabric_m,notes,created_at FROM production WHERE contract_id=? ORDER BY id DESC", (chosen["id"],))
            if prod:
                st.dataframe(pd.DataFrame(prod), hide_index=True, use_container_width=True)
            else:
                st.info("No production updates yet. Switch to Weaving Mill to add one.")
        else:
            st.info("Create a contract first.")
    with t4:
        st.subheader("Connect to a simulated mill system")
        st.caption("This is a real HTTP API integration against a separate demo mill database, not a connection to an actual ERP.")
        st.code("uvicorn mill_api:app --reload --port 8000", language="bash")
        api_url = st.text_input("Mill API base URL", value="http://127.0.0.1:8000")
        api_key = st.text_input("Demo API key", value="local-demo-key", type="password")
        if contracts:
            chosen = st.selectbox("ZWARK contract", contracts, format_func=lambda x: x["ref"], key="api_contract")
            existing = rows("SELECT mill_order_ref FROM contract_mappings WHERE contract_id=?", (chosen["id"],))
            default_order = existing[0]["mill_order_ref"] if existing else f"MILL-{chosen['ref']}"
            with st.form("mapping_form"):
                mill_ref = st.text_input("Corresponding order ID in mill system", value=default_order)
                save_mapping = st.form_submit_button("Save contract-to-mill order mapping")
            if save_mapping:
                try:
                    with connect() as db:
                        db.execute("INSERT INTO contract_mappings (contract_id,mill_order_ref) VALUES (?,?) ON CONFLICT(contract_id) DO UPDATE SET mill_order_ref=excluded.mill_order_ref", (chosen["id"], mill_ref.strip()))
                    st.success("Mapping saved")
                    st.rerun()
                except sqlite3.IntegrityError:
                    st.error("This mill order is already mapped to another contract.")
            mapping = rows("SELECT mill_order_ref FROM contract_mappings WHERE contract_id=?", (chosen["id"],))
            if mapping:
                order_ref = mapping[0]["mill_order_ref"]
                st.info(f"ZWARK {chosen['ref']} ↔ Mill order {order_ref}")
                st.markdown("**Automatic simulated mill shifts**")
                st.caption("Each click creates the next shift (Morning → Evening → Night → next day) in the independent mill database, then imports its records into ZWARK via HTTP API. No manual entry needed.")
                if st.button("Generate next shift + synchronize from mill API", type="primary"):
                    try:
                        headers = {"X-API-Key": api_key}
                        # Generate data in the external mill system, NOT in ZWARK.
                        generated = requests.post(f"{api_url.rstrip('/')}/mill/orders/{order_ref}/simulate-next-shift", headers=headers, timeout=5)
                        generated.raise_for_status()
                        new_record = generated.json()["record"]
                        r = requests.get(f"{api_url.rstrip('/')}/mill/orders/{order_ref}/shift-records", headers=headers, timeout=5)
                        r.raise_for_status()
                        records = r.json()["records"]
                        imported = skipped = rejected = duplicate_shift = 0
                        with connect() as db:
                            for rec in records:
                                exists = db.execute("SELECT 1 FROM api_imports WHERE external_record_id=? AND mill_order_ref=?", (rec["id"],order_ref)).fetchone()
                                if exists:
                                    skipped += 1
                                    continue
                                shift_exists = db.execute("SELECT 1 FROM production WHERE contract_id=? AND shift_date=? AND shift=?", (chosen["id"],rec["shift_date"],rec["shift"])).fetchone()
                                if shift_exists:
                                    duplicate_shift += 1
                                    continue
                                available = db.execute("SELECT COALESCE(SUM(received_quantity),0) FROM shipments WHERE contract_id=?",(chosen["id"],)).fetchone()[0]
                                used_so_far = db.execute("SELECT COALESCE(SUM(yarn_used+yarn_waste),0) FROM production WHERE contract_id=?",(chosen["id"],)).fetchone()[0]
                                if rec["yarn_used"] + rec["yarn_waste"] > available - used_so_far + 1e-6:
                                    rejected += 1
                                    continue
                                cursor = db.execute("INSERT INTO production (contract_id,shift_date,shift,yarn_used,yarn_waste,fabric_m,notes,created_at) VALUES (?,?,?,?,?,?,?,?)", (chosen["id"],rec["shift_date"],rec["shift"],rec["yarn_used"],rec["yarn_waste"],rec["fabric_m"],f"API import: mill record #{rec['id']}",now()))
                                db.execute("INSERT INTO api_imports (external_record_id,mill_order_ref,production_id,imported_at) VALUES (?,?,?,?)", (rec["id"],order_ref,cursor.lastrowid,now()))
                                imported += 1
                        st.success(f"Mill generated {new_record['shift_date']} / {new_record['shift']}: {new_record['yarn_used']} kg used, {new_record['yarn_waste']} kg wasted, {new_record['fabric_m']} m fabric. Imported {imported} shift(s).")
                        if rejected:
                            st.warning(f"{rejected} shift(s) not imported because there is insufficient confirmed received yarn. Confirm more receipt before retrying.")
                        if duplicate_shift:
                            st.warning(f"{duplicate_shift} external shift(s) skipped because that date/shift is already recorded in ZWARK.")
                    except (requests.RequestException, ValueError, KeyError) as exc:
                        st.error(f"Mill API generation or synchronization failed: {exc}. Ensure you restarted the mill API with the V3 files.")
                st.caption("One record per contract/date/shift in ZWARK. Imported data is simulated, not real loom telemetry.")
                imported_rows = rows("SELECT external_record_id, mill_order_ref, imported_at FROM api_imports WHERE mill_order_ref=? ORDER BY external_record_id DESC", (order_ref,))
                if imported_rows:
                    st.dataframe(pd.DataFrame(imported_rows), hide_index=True, use_container_width=True)
            else:
                st.warning("Save the contract mapping first.")
        else:
            st.info("Create a contract before setting up the API integration.")

else:
    t1,t2,t3 = st.tabs(["Incoming Shipments", "Confirm Receipt", "Production Updates"])
    with t1:
        st.subheader("Incoming yarn shipments")
        ships = rows("SELECT s.id, c.ref, c.material, c.batch, s.quantity, s.dispatched_at, s.received_quantity, s.received_at FROM shipments s JOIN contracts c ON c.id=s.contract_id ORDER BY s.id DESC")
        if ships:
            df = pd.DataFrame(ships)
            df["status"] = df["received_at"].apply(lambda x: "Received" if x else "Pending")
            st.dataframe(df[["id","ref","material","batch","quantity","dispatched_at","status","received_quantity"]], hide_index=True, use_container_width=True)
        else:
            st.info("No shipments. Switch to Yarn Supplier to dispatch yarn.")
    with t2:
        st.subheader("Confirm receipt against a shipment QR")
        st.caption("For this demo, copy the QR's encoded shipment reference or select a pending shipment. A camera scanner can be added later.")
        pending = rows("SELECT s.id, s.quantity, c.ref FROM shipments s JOIN contracts c ON c.id=s.contract_id WHERE s.received_at IS NULL ORDER BY s.id DESC")
        if pending:
            token = st.text_input("Paste QR text (optional)", placeholder="ZWARK-CONNECT|SHIPMENT:1|CONTRACT:ZW-001")
            options = {f"#{s['id']} · {s['ref']} · {s['quantity']:,.1f} kg":s for s in pending}
            chosen_label = st.selectbox("Or select pending shipment", list(options))
            selected = options[chosen_label]
            if token.strip():
                matched = [s for s in pending if token.strip() == f"ZWARK-CONNECT|SHIPMENT:{s['id']}|CONTRACT:{s['ref']}"]
                if matched:
                    selected = matched[0]
                    st.success(f"QR matched shipment #{selected['id']} ({selected['ref']}).")
                else:
                    st.error("QR reference does not match a pending shipment. Receipt is disabled.")
            valid = not token.strip() or bool([s for s in pending if token.strip() == f"ZWARK-CONNECT|SHIPMENT:{s['id']}|CONTRACT:{s['ref']}"])
            with st.form("receive_form"):
                received_qty = st.number_input("Quantity physically received (kg)", min_value=0.0, max_value=float(selected["quantity"]), value=float(selected["quantity"]), key=f"receive_qty_{selected['id']}")
                confirm = st.form_submit_button("Confirm receipt", type="primary", disabled=not valid)
            if confirm:
                with connect() as db:
                    db.execute("UPDATE shipments SET received_quantity=?,received_at=? WHERE id=? AND received_at IS NULL", (received_qty,now(),selected["id"]))
                st.success("Receipt confirmed and visible to the supplier.")
                st.rerun()
        else:
            st.info("No pending shipments.")
    with t3:
        st.subheader("Record shift-wise production and wastage")
        if contracts:
            chosen = st.selectbox("Contract", contracts, format_func=lambda x: f"{x['ref']} · {x['batch']}", key="mill_progress")
            received = scalar("SELECT COALESCE(SUM(received_quantity),0) FROM shipments WHERE contract_id=?", (chosen["id"],))
            used = scalar("SELECT COALESCE(SUM(yarn_used),0) FROM production WHERE contract_id=?", (chosen["id"],))
            waste = scalar("SELECT COALESCE(SUM(yarn_waste),0) FROM production WHERE contract_id=?", (chosen["id"],))
            balance = max(0.0, received-used-waste)
            st.metric("Received yarn available for recording", f"{balance:,.1f} kg")
            if received <= 0:
                st.info("Confirm receipt of a shipment before recording production.")
            elif balance <= 0:
                st.info("All received yarn is accounted for. Receive more yarn to record additional usage.")
            else:
                with st.form("production_form", clear_on_submit=True):
                    date = st.date_input("Shift date")
                    shift = st.selectbox("Shift", ["Morning", "Evening", "Night"])
                    used_qty = st.number_input("Yarn used in production (kg)", min_value=0.0, value=0.0, step=1.0)
                    waste_qty = st.number_input("Yarn wasted (kg)", min_value=0.0, value=0.0, step=1.0)
                    fabric_m = st.number_input("Fabric produced (meters)", min_value=0.0, value=0.0, step=10.0)
                    notes = st.text_input("Notes (optional)")
                    save = st.form_submit_button("Save production update", type="primary")
                if save:
                    if used_qty + waste_qty > balance + 1e-6:
                        st.error("Yarn used plus wasted cannot exceed received yarn remaining.")
                    elif used_qty == 0 and waste_qty == 0 and fabric_m == 0:
                        st.error("Enter at least one production value.")
                    elif scalar("SELECT COUNT(*) FROM production WHERE contract_id=? AND shift_date=? AND shift=?", (chosen["id"],str(date),shift)):
                        st.error("This contract already has a record for that date and shift. Only one row per shift is allowed.")
                    else:
                        with connect() as db:
                            db.execute("INSERT INTO production (contract_id,shift_date,shift,yarn_used,yarn_waste,fabric_m,notes,created_at) VALUES (?,?,?,?,?,?,?,?)", (chosen["id"],str(date),shift,used_qty,waste_qty,fabric_m,notes.strip(),now()))
                        st.success("Production update saved and shared with supplier.")
                        st.rerun()
            history = rows("SELECT shift_date,shift,yarn_used,yarn_waste,fabric_m,notes FROM production WHERE contract_id=? ORDER BY id DESC", (chosen["id"],))
            if history:
                st.dataframe(pd.DataFrame(history), hide_index=True, use_container_width=True)
        else:
            st.info("Create a supplier contract first.")

st.divider()
st.caption("ZWARK Connect  · Simulated mill API integration only. ")
